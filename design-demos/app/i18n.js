  function translateText(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach((node) => {
      const parent = node.parentElement;
      if (!parent) return;
      const tag = parent.tagName;
      if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'TITLE') return;
      const raw = node.nodeValue;
      if (!raw || !raw.trim()) return;
      if (lang === 'en') {
        if (!origText.has(node)) origText.set(node, raw);
        const src = origText.get(node);
        const key = src.trim();
        if (!/[\u4e00-\u9fa5]/.test(key)) return;
        const tr = I18N[key] || ruleTranslate(key);
        if (tr) {
          const next = src.replace(key, tr);
          if (node.nodeValue !== next) node.nodeValue = next;
        }
      } else if (origText.has(node)) {
        const back = origText.get(node);
        if (node.nodeValue !== back) node.nodeValue = back;
      }
    });
  }

